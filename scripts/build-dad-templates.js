// Generate src/dad-templates.js from docs/dad-chat/file-templates/ so Studio can offer the starter files offline.
// The docs folder is the source of truth; run `npm run build` after changing a template.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'docs', 'dad-chat', 'file-templates');
const out = path.join(root, 'src', 'dad-templates.js');
// file prefix -> [label, direction, detect kind, group]. Order follows the numbered files.
const meta = {
  '01': ['Dad-native character (dad-char)', 'export + import', 'dad-char', 'dad'],
  '02': ['Character + one chat (dad-char-chat)', 'export + import', 'dad-char-chat', 'dad'],
  '03': ['Full backup (dad-full)', 'export + import', 'dad-full', 'dad'],
  '04': ['World file (dad-world)', 'export + import', 'dad-world', 'dad'],
  '05': ['Character lorebook (Dad-native)', 'export + import', 'lorebook', 'dad'],
  '06': ['Standalone lorebook (Dad-native)', 'export + import', 'lorebook', 'dad'],
  '07': ['Single lore entry (authoring fragment)', 'authoring', '', 'dad'],
  '08': ['Tavern V1 flat card', 'import only', 'card', 'share'],
  '09': ['Tavern V2 card (chara_card_v2)', 'export + import', 'card', 'share'],
  '10': ['Forge character card (V2 + forge)', 'export + import', 'card', 'share'],
  '11': ['Forge lorebook file', 'export + import', 'lorebook', 'share'],
  '12': ['SillyTavern World Info', 'import only', 'worldinfo', 'share'],
  '13': ['Bare V2 character book', 'import only', 'lorebook', 'share'],
  '14': ['JanitorAI lore array', 'import only', '', 'share'],
  '15': ['Perchance dexie character export', 'import only', '', 'share'],
  '16': ['Generic chat log (messages array)', 'import only', '', 'share'],
  '17': ['Chat transcript (plain)', 'export', '', 'chat'],
  '18': ['Chat transcript (with header)', 'export', '', 'chat'],
  '19': ['User profile (dad-user-profile)', 'export + import', 'dad-user-profile', 'dad'],
  '20': ['Cloud Backup mirror file', 'export', '', 'chat'],
  '21': ['Story Forge character list', 'export + import', 'forge-cast', 'share'],
  '22': ['Hub publish payload (dad-char v3)', 'publish', 'dad-char', 'dad'],
  '23': ['Weld AI request', 'wire', '', 'weld'],
  '24': ['Weld AI result', 'wire', '', 'weld'],
  '25': ['Weld model info result', 'wire', '', 'weld'],
  '26': ['Weld storage link record', 'wire', '', 'weld'],
  '27': ['Weld bus envelope', 'wire', '', 'weld'],
  '28': ['Vault save (Weld storage)', 'wire', '', 'weld']
};
const files = fs.readdirSync(dir).filter(f => /^\d\d-/.test(f)).sort();
const rows = files.map(f => {
  const m = meta[f.slice(0, 2)];
  if (!m) throw new Error('No metadata for template ' + f + '. Add it to scripts/build-dad-templates.js.');
  const text = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n');
  return { file: f, label: m[0], direction: m[1], detect: m[2], group: m[3], text };
});
const body = `/* GENERATED by scripts/build-dad-templates.js from docs/dad-chat/file-templates/. Do not edit by hand.
   Starter files for every shape Dad Chat reads and writes. Plain data: no DOM, network or storage. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.WeldDadTemplates = factory();
})(typeof window === 'object' ? window : globalThis, function () {
  'use strict';
  const rows = ${JSON.stringify(rows, null, 2)};
  return Object.freeze({ rows: Object.freeze(rows.map(r => Object.freeze(r))), byFile: Object.freeze(rows.reduce((m, r) => { m[r.file] = r; return m; }, {})) });
});
`;
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== body) { console.error('src/dad-templates.js is stale. Run npm run build.'); process.exitCode = 1; } else console.log('Dad templates match docs.');
} else fs.writeFileSync(out, body);
